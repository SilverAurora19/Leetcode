# LeetCode 78: 子集 (Subsets)
#
# 题目：给定一个不含重复数字的数组 nums，返回其所有可能的子集（幂集）。
# 子集是无序的——[1,2] 和 [2,1] 是同一个子集，不能重复。
#
# 核心思路（回溯 / DFS + start_index）：
# 全排列和子集最大的区别在于"是否考虑顺序"：
#   - 全排列：顺序重要 → 用 used 数组，每次从"所有未用过的"里面选
#   - 子集：  顺序不重要 → 用 start_index，每次只从"当前位置之后"选，避免选出重复组合
#
# 为什么 start_index 能避免重复？
#   例如 nums = [1, 2, 3]：
#   选了 1 之后，只能从 2、3 中继续选 → 不会出现 [2,1]（因为 2 之后不能回头选 1）
#   这样 [1,2] 只会被生成一次，而不会再有 [2,1]。
#
# 另一个关键区别：每个节点都要收集，不只是叶子！
#   全排列：只有走到终点（排列长度 == n）才收集结果
#   子集：  空集、每个中间状态都是合法的子集，所以一进入递归就收集
#
# 决策树（nums = [1, 2, 3]）：
#
#                         []                   ← 空集
#               /         |         \
#             [1]        [2]        [3]        ← 选第1个元素（start=0）
#            /   \        |
#         [1,2] [1,3]   [2,3]                  ← 选第2个元素（start=前一个位置+1）
#          |
#       [1,2,3]                                ← 选第3个元素
#
#   总共 2³ = 8 个子集（每个元素"选或不选"两种可能）
#   结果：[[],[1],[1,2],[1,2,3],[1,3],[2],[2,3],[3]]
#
# 时间复杂度：O(n × 2^n)——2^n 个子集，每个子集平均长度 n/2（复制开销）
# 空间复杂度：O(n)——递归栈深度 + path 数组

class Solution(object):
    def subsets(self, nums):
        """
        :type nums: List[int]
        :rtype: List[List[int]]   # 所有子集（幂集）
        """
        result = []
        path = []    # 当前正在构建的子集

        def backtrack(start_index):
            """
            回溯：从 start_index 开始，选择元素加入子集。
            start_index 保证只向后选，避免生成 [1,2] 和 [2,1] 这种重复。
            """
            # ★ 每个节点都是一个合法子集，直接收集
            #   （用 path[:] 复制，因为 path 后续会被 pop 修改）
            result.append(path[:])

            # 从 start_index 开始向后选，保证每个元素只被考虑一次
            for i in range(start_index, len(nums)):
                # === 做选择 ===
                path.append(nums[i])

                # 递归：下一个位置只能从 i+1 开始（不回头，避免重复组合）
                backtrack(i + 1)

                # === 撤销选择（回溯）===
                path.pop()

        backtrack(0)
        return result
