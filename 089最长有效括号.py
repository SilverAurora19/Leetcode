# LeetCode 32: 最长有效括号 (Longest Valid Parentheses)
#
# 题目：给定只含 '(' 和 ')' 的字符串，找出最长的"有效括号子串"的长度。
# 有效括号：每个左括号都有对应的右括号，且配对正确。
#
# 核心思路（栈存下标）：
# 用栈存"下标"（不是字符本身），栈底始终保持"最后一个无法配对的右括号的下标"，
# 作为计算长度的基准。
#
# 初始化：栈里先放 -1，表示"有效子串起始位置的前一个位置"。
#
# 遍历每个字符：
#   - 遇到 '(' → 把它的下标压栈（等待配对）
#   - 遇到 ')' → 弹出栈顶：
#       * 弹出后栈为空 → 说明这个 ')' 无法配对，把它的下标压栈（成为新基准）
#       * 弹出后栈非空 → 当前有效长度 = 当前下标 i - 栈顶下标
#
# 例如：s = ")()())"
#   初始：栈 = [-1]
#   i=0 ')': 弹 -1，栈空 → 压 0，栈=[0]（这个 ) 无法配对，是基准）
#   i=1 '(': 压 1，栈=[0,1]
#   i=2 ')': 弹 1，栈非空 → 长度 = 2-0 = 2，栈=[0]
#   i=3 '(': 压 3，栈=[0,3]
#   i=4 ')': 弹 3，栈非空 → 长度 = 4-0 = 4，栈=[0]（"()()" 长度4）
#   i=5 ')': 弹 0，栈空 → 压 5，栈=[5]
#   最长 = 4 ✓
#
# 时间复杂度：O(n)
# 空间复杂度：O(n)——栈

class Solution:
    def longestValidParentheses(self, s):
        """
        :type s: str
        :rtype: int   # 最长有效括号子串的长度
        """
        stack = [-1]   # 栈底放 -1，作为"有效子串起点前一个位置"的基准
        max_len = 0

        for i, ch in enumerate(s):
            if ch == '(':
                # 左括号压栈，等待右括号来配对
                stack.append(i)
            else:
                # 右括号：先弹出栈顶（尝试配对）
                stack.pop()

                if not stack:
                    # 弹出后栈空 → 这个 ')' 无法配对，成为新的基准
                    stack.append(i)
                else:
                    # 栈非空 → 当前有效长度 = i - 栈顶下标
                    max_len = max(max_len, i - stack[-1])

        return max_len
