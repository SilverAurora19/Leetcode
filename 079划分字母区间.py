# LeetCode 763: 划分字母区间 (Partition Labels)
#
# 题目：把字符串分成尽可能多的片段，要求每个字母只出现在其中一个片段中。
# 返回每个片段的长度。
#
# 核心思路（贪心 + 记录最后出现位置）：
# 1. 先扫一遍，记录每个字母"最后一次出现的位置"。
# 2. 再扫一遍，维护当前片段的结束边界 end：
#    - 遇到一个字母，它的最后出现位置必须包含在当前片段内，
#      所以 end = max(end, last[ch])（不断向右扩展）
#    - 当遍历到 i == end 时，说明当前片段已经"收口"——所有字母都不再往后出现，
#      可以切分了，记录长度，开始下一个片段。
#
# 直觉理解：
#   一个片段从 start 开始，只要里面的字母还有更晚的出现，就不能切，
#   所以 end 要一直扩张到"片段内所有字母的最后出现位置"的最大值。
#
# 例如：s = "ababcbacadefegdehijhklij"
#   各字母最后出现位置：
#     a→8, b→5, c→7, d→14, e→15, f→11, g→13, h→19, i→22, j→23, k→20, l→21
#
#   从 start=0 开始：
#     a(0)→end=8, b(1)→end=8, a(2)→8, b(3)→8, c(4)→8, b(5)→8,
#     a(6)→8, c(7)→8, a(8)→8, i==end=8 → 切分 [0,8] 长度9 ✓
#   从 start=9 开始：
#     d(9)→14, e(10)→15, f(11)→15, e(12)→15, g(13)→15, d(14)→15,
#     e(15)→15, i==15 → 切分 [9,15] 长度7 ✓
#   依此类推 → [9, 7, 8]
#
# 时间复杂度：O(n)
# 空间复杂度：O(1)——最多 26 个字母

class Solution:
    def partitionLabels(self, s):
        """
        :type s: str
        :rtype: List[int]   # 每个片段的长度
        """
        # 第1步：记录每个字母最后一次出现的位置
        last = {}
        for i, ch in enumerate(s):
            last[ch] = i   # 后出现的会覆盖前面的，最终留下最后位置

        res = []
        start = 0   # 当前片段的起始位置
        end = 0     # 当前片段的结束边界（会不断向右扩张）

        # 第2步：贪心切分
        for i, ch in enumerate(s):
            # 当前字母的最后出现位置必须包含进来，扩展 end
            end = max(end, last[ch])

            # 走到 end：片段内所有字母都不会再往后出现了 → 切分
            if i == end:
                res.append(end - start + 1)   # 记录片段长度
                start = end + 1               # 下一个片段从这里开始

        return res
