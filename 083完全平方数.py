# LeetCode 279: 完全平方数 (Perfect Squares)
#
# 题目：给定正整数 n，求最少需要多少个"完全平方数"（1, 4, 9, 16, ...）相加得到 n。
# 例如 n=12 = 4+4+4，最少 3 个。
#
# 核心思路（动态规划，同 084 零钱兑换）：
# 这道题其实就是"零钱兑换"的变体——把"硬币"换成"完全平方数"。
# dp[i] = 凑成数字 i 所需的最少完全平方数个数。
#
# 递推公式：
#   dp[i] = min(1 + dp[i - j²])  对于所有 j² ≤ i
#   即：凑 i 的最优解 = 先用最少的平方数凑 i - j²，再加一个 j²
#
# 例如：n = 12
#   dp[0] = 0
#   dp[1] = 1（1）
#   dp[4] = 1（4）
#   dp[9] = 1（9）
#   ...
#   dp[12]：试 j²=1 → 1+dp[11]，j²=4 → 1+dp[8]，j²=9 → 1+dp[3]
#          dp[3]=3（1+1+1），所以 1+dp[3]=4
#          但 j²=4 时 1+dp[8]=1+2=3（8=4+4）→ 最优 3 ✓
#
# 时间复杂度：O(n × √n)——对每个 i 要试 √i 个平方数
# 空间复杂度：O(n)——dp 数组

class Solution:
    def numSquares(self, n):
        """
        :type n: int
        :rtype: int   # 组成 n 的最少完全平方数个数
        """
        dp = [float('inf')] * (n + 1)   # dp[i] = 组成 i 的最少个数，初始无穷大
        dp[0] = 0                        # 组成 0 需要 0 个

        for i in range(1, n + 1):
            j = 1
            # 枚举所有不超过 i 的完全平方数 j²
            while j * j <= i:
                square = j * j
                # 用一个 j² + 组成 i-j² 的最少个数
                dp[i] = min(dp[i], 1 + dp[i - square])
                j += 1

        return dp[n]
