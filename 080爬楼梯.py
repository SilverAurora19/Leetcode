# LeetCode 70: 爬楼梯 (Climbing Stairs)
#
# 题目：有 n 级台阶，每次可以爬 1 级或 2 级，问有多少种不同的爬法。
#
# 核心思路（动态规划 / 斐波那契数列）：
# 爬到第 n 级台阶，最后一步要么从 n-1 级跳 1 级，要么从 n-2 级跳 2 级。
# 所以：f(n) = f(n-1) + f(n-2)
# 这正好是斐波那契数列！
#
# 边界：f(1) = 1（只有一步跳 1 级）
#       f(2) = 2（1+1 或 2）
#
# 例如：n = 4
#   f(1) = 1
#   f(2) = 2
#   f(3) = f(2) + f(1) = 2 + 1 = 3
#   f(4) = f(3) + f(2) = 3 + 2 = 5
#   5 种爬法：
#     1+1+1+1, 1+1+2, 1+2+1, 2+1+1, 2+2
#
# 为什么用迭代而不是递归？
#   递归会重复计算很多子问题（指数级），迭代 O(n) 且只用两个变量。
#
# 时间复杂度：O(n)
# 空间复杂度：O(1)——只用了 a、b 两个变量

class Solution:
    def climbStairs(self, n):
        """
        :type n: int
        :rtype: int   # 爬到第 n 级台阶的方法数
        """
        # 边界情况：1 级 1 种，2 级 2 种
        if n <= 2:
            return n

        # a 代表 f(n-2)，b 代表 f(n-1)，初始 a=1, b=2（即 f(1), f(2)）
        a, b = 1, 2
        for _ in range(3, n + 1):   # 从第 3 级算到第 n 级
            a, b = b, a + b         # 滚动更新：新的 b = 旧的 a + 旧的 b

        return b   # 循环结束后 b 就是 f(n)
