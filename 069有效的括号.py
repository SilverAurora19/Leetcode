# LeetCode 20: 有效的括号 (Valid Parentheses)
#
# 题目：判断字符串中的括号是否全部正确配对闭合。
# 有效示例："()[]{}"、"{[]}"
# 无效示例："(]"，"([)]"，"(("
#
# 核心思路（栈）：
# 遇到左括号 → 压栈；遇到右括号 → 弹出栈顶，检查是否匹配。
# 栈的"后进先出"特性天然匹配括号的"就近配对"规则：
# 最近一个左括号必须最先被对应的右括号闭合。
#
# 用字典把"右括号 → 对应的左括号"映射起来，方便判断配对。
#
# 例如：s = "{[]}"
#   '{' 是左括号 → 压栈 [ '{' ]
#   '[' 是左括号 → 压栈 [ '{', '[' ]
#   ']' 是右括号 → 弹栈顶 '['，匹配 ']' ✓
#   '}' 是右括号 → 弹栈顶 '{'，匹配 '}' ✓
#   栈空 → 全部匹配 ✓
#
# 反例：s = "([)]"
#   '(' 压栈 → '[' 压栈 → 栈 [ '(', '[' ]
#   ')' 右括号 → 弹栈顶 '['，但 '[' ≠ '(' ✗ → 返回 False
#
# 时间复杂度：O(n)
# 空间复杂度：O(n)——最坏情况栈存 n 个左括号

class Solution:
    def isValid(self, s):
        """
        :type s: str
        :rtype: bool
        """
        stack = []

        # 字典：右括号 → 对应的左括号（修：用冒号而非等号）
        pairs = {
            ')': '(',
            ']': '[',
            '}': '{',
        }

        for char in s:
            if char in pairs:
                # 是右括号
                if not stack:
                    # 栈空却来了右括号 → 没有左括号可配对 → 无效
                    return False

                top = stack.pop()          # 弹出最近的左括号

                if top != pairs[char]:
                    # 栈顶左括号和当前右括号不配对 → 无效
                    return False
            else:
                # 是左括号 → 压栈
                stack.append(char)

        # 遍历结束，栈必须为空才说明所有左括号都被正确闭合
        return len(stack) == 0
