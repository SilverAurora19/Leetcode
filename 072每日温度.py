# LeetCode 739: 每日温度 (Daily Temperatures)
#
# 题目：对于每一天，求"还要等几天才能遇到更暖和的温度"。
# 如果之后都没有更暖的，就是 0。
#
# 核心思路（单调栈，存下标）：
# 维护一个"单调递减"的栈（存的是下标，栈底到栈顶温度递减）。
# 栈里的每一天都在"等待一个比它更暖的日子"。
#
# 遍历每一天的温度：
#   当前温度比栈顶高 → 栈顶等待的日子终于等到了！
#       弹出栈顶 j，答案 ans[j] = i - j（等了多少天）
#       继续和新的栈顶比较（可能一下解决好几天）
#   把当前下标 i 压栈（它自己也开始等待更暖的日子）
#
# 例如：temps = [73, 74, 75, 71, 69, 72, 76, 73]
#
#   i=0(73)：栈空 → 压0，栈[0]
#   i=1(74)：74>73 → 弹0，ans[0]=1，压1，栈[1]
#   i=2(75)：75>74 → 弹1，ans[1]=1，压2，栈[2]
#   i=3(71)：71<75 → 压3，栈[2,3]
#   i=4(69)：69<71 → 压4，栈[2,3,4]
#   i=5(72)：72>69 → 弹4，ans[4]=1；72>71 → 弹3，ans[3]=2；压5，栈[2,5]
#   i=6(76)：76>72 → 弹5，ans[5]=1；76>75 → 弹2，ans[2]=4；压6，栈[6]
#   i=7(73)：73<76 → 压7，栈[6,7]
#
#   结果：[1, 1, 4, 2, 1, 1, 0, 0]
#
# 时间复杂度：O(n)——每个下标入栈一次、出栈一次
# 空间复杂度：O(n)——栈最多存 n 个下标

class Solution:
    def dailyTemperatures(self, temps):
        """
        :type temps: List[int]
        :rtype: List[int]   # ans[i] = 第 i 天要等几天才有更暖温度
        """
        n = len(temps)
        stack = []           # 单调递减栈，存"还没找到更暖日子"的下标
        ans = [0] * n        # 结果数组，默认 0（表示之后没有更暖的）

        for i in range(n):
            # 当前温度比栈顶温度高 → 栈顶的天数终于等到更暖的日子
            while stack and temps[i] > temps[stack[-1]]:
                j = stack.pop()          # 弹出等待已久的下标
                ans[j] = i - j           # 记录等了几天

            # 当前下标也入栈，开始等待更暖的日子
            stack.append(i)

        return ans
