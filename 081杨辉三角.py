# LeetCode 118: 杨辉三角 (Pascal's Triangle)
#
# 杨辉三角的规则：每个数是它左上方和右上方两个数之和，两端都是 1。
#
#     1
#    1 1
#   1 2 1
#  1 3 3 1
# 1 4 6 4 1
#
# 核心思路（相邻相加，两端补 0 的技巧）：
# 生成下一行时，把上一行两端各补一个 0：
#   [0] + 上一行 + [0]
# 然后相邻两个数相加，就得到新的一行。
#
# 为什么补 0 就能得到正确结果？
#   上一行 [1, 3, 3, 1] 补 0 后是 [0, 1, 3, 3, 1, 0]
#   相邻相加：0+1=1, 1+3=4, 3+3=6, 3+1=4, 1+0=1
#   → [1, 4, 6, 4, 1] ✓ 正好是下一行，两端自然得到 1（因为 0 + 1 = 1）
#
# 例如：numRows = 5
#   第1行：[1]
#   第2行：[0,1,0] 相邻相加 → [1,1]
#   第3行：[0,1,1,0] → [1,2,1]
#   第4行：[0,1,2,1,0] → [1,3,3,1]
#   第5行：[0,1,3,3,1,0] → [1,4,6,4,1]
#
# 时间复杂度：O(numRows²)——总共生成约 n²/2 个数
# 空间复杂度：O(1)——不计结果数组

class Solution:
    def generate(self, numRows):
        """
        :type numRows: int
        :rtype: List[List[int]]   # 杨辉三角的前 numRows 行
        """
        res = [[1]]   # 第一行固定为 [1]

        # 需要生成 numRows-1 次（每次在已有基础上加一行）
        for i in range(numRows - 1):
            # 上一行两端补 0，方便相邻相加（两端自然得到 1）
            temp = [0] + res[-1] + [0]

            row = []
            # 新行的长度 = 上一行长度 + 1
            for j in range(len(res[-1]) + 1):
                # 相邻两个数相加
                row.append(temp[j] + temp[j + 1])

            res.append(row)

        return res
