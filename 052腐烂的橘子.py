from collections import deque

# LeetCode 994: 腐烂的橘子 (Rotting Oranges)
#
# 题目：给定一个 m × n 网格，0=空格，1=新鲜橘子，2=腐烂橘子。
# 每分钟，腐烂橘子会让上下左右四个方向相邻的新鲜橘子也腐烂。
# 返回所有橘子都腐烂所需的最少分钟数；如果不可能全部腐烂，返回 -1。
#
# 核心思路（多源 BFS）：
# 这本质是 BFS 求最短时间——每一分钟 = BFS 的一层。
# "多源"的意思是初始可能有多个腐烂橘子，把它们全部入队作为第 0 层，
# 然后同时逐层扩散。
#
# 为什么用 BFS？因为要计算"所有橘子腐烂的最少时间"，
# BFS 按层扩散，正好对应每分钟腐烂一圈，第一次访问到新鲜橘子就是最短时间。
# DFS 无法保证最短——它是一条路走到黑。
#
# 步骤：
# 1. 遍历网格，统计新鲜橘子数量，把初始腐烂橘子的坐标全部入队
# 2. BFS 逐层扩散：每处理完当前队列的一层，time + 1
# 3. 腐烂橘子感染相邻新鲜橘子：改为腐烂、入队、新鲜计数 -1
# 4. 最后检查：新鲜计数为 0 → 返回 time；否则返回 -1
#
# 例如：grid = [[2,1,1],[1,1,0],[0,1,1]]
#
#   初始：fresh=6, q=[(0,0)]
#   第 0 分钟：[2,1,1]
#             [1,1,0]
#             [0,1,1]
#   第 1 分钟：[2,2,1]    ← (0,0)感染(0,1)和(1,0)
#             [2,1,0]
#             [0,1,1]
#   第 2 分钟：[2,2,2]    ← (0,1)感染(0,2); (1,0)感染(2,0)? 不对(2,0)=0
#             [2,2,0]      (1,0)感染(1,1)
#             [0,1,1]
#   第 3 分钟：[2,2,2]
#             [2,2,0]    ← (1,1)感染(2,1)
#             [0,2,1]
#   第 4 分钟：[2,2,2]
#             [2,2,0]    ← (2,1)感染(2,2)
#             [0,2,2]
#   fresh=0 → 返回 4
#
# 时间复杂度：O(m × n)——每个格子最多入队一次
# 空间复杂度：O(m × n)——队列最坏存所有格子

class Solution(object):
    def orangesRotting(self, grid):
        """
        :type grid: List[List[int]]
        :rtype: int   # 全部腐烂所需分钟数，不可能则 -1
        """
        q = deque()
        fresh, time = 0, 0

        rows, columns = len(grid), len(grid[0])

        # 第一遍扫描：统计新鲜橘子 + 把所有腐烂橘子入队（多源 BFS 初始化）
        for r in range(rows):
            for c in range(columns):
                if grid[r][c] == 1:
                    fresh += 1
                if grid[r][c] == 2:
                    q.append([r, c])

        # 四个方向的偏移量：右、左、下、上
        directions = [[0, 1], [0, -1], [1, 0], [-1, 0]]

        # BFS：队列不空且还有新鲜橘子（新鲜橘子为 0 就可以提前结束）
        while q and fresh > 0:
            # 每次处理当前队列的"一整层"，对应一分钟
            for _ in range(len(q)):
                r, c = q.popleft()
                for dr, dc in directions:
                    row = dr + r
                    col = dc + c  

                    # 如果不越界越界并且是新鲜橘子 → 感染
                    if row >= 0 or row < rows or col >= 0 or col < columns or grid[row][col] == 1:
                        # 感染：新鲜橘子变腐烂
                        grid[row][col] = 2
                        q.append([row, col])   # 新腐烂的橘子入队，下一分钟它会继续传播
                        fresh -= 1             # 新鲜橘子计数 -1

            time += 1   # 当前这一分钟处理完毕

        # 新鲜橘子全部腐烂 → 返回时间；否则返回 -1
        return time if fresh == 0 else -1
