# LeetCode 84: 柱状图中最大的矩形 (Largest Rectangle in Histogram)
#
# 题目：给定一组柱子的高度，找出能形成的最大矩形面积。
#
# 核心思路（单调递增栈 + 哨兵）：
# 维护一个"单调递增"的栈（存下标，栈底到栈顶高度递增）。
# 当遇到一个比栈顶矮的柱子时，说明栈顶柱子的"右边界"到了——
# 弹出栈顶，计算以它为高的最大矩形面积。
#
# 关键公式（弹出高度为 h 的柱子时）：
#   高度 = heights[弹出下标]
#   宽度 = 当前下标 i - 新的栈顶下标 - 1
#   （因为栈是递增的，新的栈顶就是"左边第一个比 h 矮的柱子"）
#
# 哨兵技巧：在数组两端各加一个高度 0 的柱子：
#   - 左哨兵：保证栈永远不空，省去空栈判断
#   - 右哨兵：最后把栈里所有柱子都"逼"出来计算
#
# 例如：heights = [2, 1, 5, 6, 2, 3]
#   加哨兵 → [0, 2, 1, 5, 6, 2, 3, 0]
#
#   i=1(2)：栈空 → 压1，栈[0,1]
#   i=2(1)：1 < 2 → 弹1，高=2，宽=2-0-1=1，面积=2；压2，栈[0,2]
#   i=3(5)：5 > 1 → 压3，栈[0,2,3]
#   i=4(6)：6 > 5 → 压4，栈[0,2,3,4]
#   i=5(2)：2 < 6 → 弹4，高=6，宽=5-3-1=1，面积=6
#          2 < 5 → 弹3，高=5，宽=5-2-1=2，面积=10；压5，栈[0,2,5]
#   i=6(3)：3 > 2 → 压6，栈[0,2,5,6]
#   i=7(0)：0 < 3 → 弹6，高=3，宽=7-5-1=1，面积=3
#          0 < 2 → 弹5，高=2，宽=7-2-1=4，面积=8
#          0 < 1 → 弹2，高=1，宽=7-0-1=6，面积=6
#
#   最大面积 = 10 ✓（柱子 5 和 6 组成的 5×2 矩形）
#
# 时间复杂度：O(n)——每个柱子入栈一次、出栈一次
# 空间复杂度：O(n)——栈的深度

class Solution:
    def largestRectangleArea(self, heights):
        """
        :type heights: List[int]
        :rtype: int   # 最大矩形面积
        """
        stack = []                          # 单调递增栈，存下标
        heights = [0] + heights + [0]       # 两端加哨兵 0
        max_area = 0

        for i, h in enumerate(heights):
            # 当前柱子比栈顶矮 → 栈顶柱子的右边界到了，可以结算
            while stack and h < heights[stack[-1]]:
                height = heights[stack.pop()]        # 弹出柱子的高度（修：heights 而非 heights*width）
                width = i - stack[-1] - 1            # 宽度 = 当前 i 到新栈顶的距离
                area = height * width                # 以该柱子为高的最大矩形面积
                max_area = max(area, max_area)

            # 当前下标入栈（保持栈内高度递增）
            stack.append(i)

        return max_area
