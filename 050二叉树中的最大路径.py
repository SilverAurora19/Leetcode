# LeetCode 124: 二叉树中的最大路径和 (Binary Tree Maximum Path Sum)
#
# 题目：给定一棵二叉树，找出任意一条路径（至少包含一个节点）的最大路径和。
# 路径可以从任意节点出发，到任意节点结束，但必须沿着父子连线走（不能回头），
# 且每个节点最多经过一次。
#
# 核心思路（递归 + 后序遍历 + 全局最大值）：
# 这道题的关键是区分"两种路径"：
#
# 1. "可向上延伸"的路径（单边路径）：
#    从当前节点出发，要么走左边，要么走右边（只能选一边！）
#    因为如果选了左右两边，再往父节点走就会走重复的边。
#    返回值 = node.val + max(left_gain, right_gain)
#    这才是 dfs 函数的返回值——供父节点使用。
#
# 2. "以当前节点为顶点"的路径（完整路径）：
#    当前节点作为这条路径的最高点，左右子树都可以取。
#    path_sum = node.val + left_gain + right_gain
#    这不会继续往上传，而是直接和全局最大值比较、更新。
#
# 负数的处理：
#   如果子树的最大贡献是负数，那宁可不要它（取 0）。
#   例如子树返回 -5，说明走那边反而拖累总和 → max(0, dfs(...))
#
# 例如：root = [-10, 9, 20, null, null, 15, 7]
#
#         -10          ← 根节点
#        /   \
#       9    20        ← 9: 单边=9, 顶点=9
#           /  \         20: 单边=20+max(15,7)=35, 顶点=20+15+7=42
#         15    7      ← 15: 单边=15, 顶点=15
#                         7: 单边=7, 顶点=7
#
#   节点 15：left=0, right=0 → 顶点=15, 单边返回=15
#   节点 7： left=0, right=0 → 顶点=7,  单边返回=7
#   节点 20：left=15, right=7 → 顶点=20+15+7=42 ★ 全局最大
#            单边返回=20+max(15,7)=35 → 传给 -10
#   节点 9： left=0, right=0 → 顶点=9, 单边返回=9
#   节点 -10：left=9, right=35 → 顶点=-10+9+35=34
#            单边返回=-10+35=25（如果继续往上，但其实它是根）
#
#   遍历过程中 global_max = max(-inf, 15, 7, 42, 9, 34) = 42 ← 答案
#   路径：15 → 20 → 7（以 20 为顶点的完整路径）
#
# 时间复杂度：O(n)——每个节点访问一次
# 空间复杂度：O(h)——递归调用栈深度，h 为树高

class Solution(object):
    def maxPathSum(self, root):
        """
        :type root: TreeNode | None
        :rtype: int   # 二叉树中任意路径的最大路径和
        """
        # 全局最大值，初始化为负无穷（处理全是负数的情况）
        self.max_sum = float('-inf')

        def dfs(node):
            """
            后序遍历：返回以 node 为起点的"最大单边贡献值"（只能走一边，供父节点使用）。
            同时，在内部更新以 node 为顶点的"完整路径和"到全局最大值。
            """
            # 空节点贡献为 0（不影响路径和）
            if node is None:
                return 0

            # 递归计算左右子树的最大贡献
            # 和 0 取 max：如果子树贡献为负，宁可不要它
            left = max(dfs(node.left), 0)
            right = max(dfs(node.right), 0)

            # "完整路径"：以当前节点为顶点，左右都取
            # 这条路径不能再往上延伸了，直接和全局最大值比较
            current_path = node.val + left + right
            self.max_sum = max(self.max_sum, current_path)

            # "单边路径"：返回给父节点用，只能选左右中的一边
            # 如果左右都走，到了父节点就没法继续了（会走重复边）
            return max(left, right) + node.val

        dfs(root)

        return self.max_sum
